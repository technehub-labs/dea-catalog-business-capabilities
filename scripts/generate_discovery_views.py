#!/usr/bin/env python3
"""generate_discovery_views.py: derived capability discovery views (CR-DEA-BC-47).

Deterministic generator rendering committed markdown views from canonical
records. Derivation contracts are specified in
docs/BUSINESS-CAPABILITY-DISCOVERY-VIEWS.md (§ of that doc = the contract per
view). Principles (CR-47 §4): canonical data authoritative; reproducible
derivation; no semantic inference (no relationship is inferred from names,
shared classification, or co-occurrence); limitations reported, never papered
over; views never redefine the model.

Views emitted (docs/views/):
- CAPABILITY-INDEX.md      navigable inventory (id, name, definition, primary
                           ECF, provenance summary, links to record + README)
- ECF-CLASSIFICATION.md    capabilities grouped by governed ECF coordinate
- RELATED-CAPABILITIES.md  recorded (untyped) related-capability references
- OUTCOMES-OVERVIEW.md     outcome + business-object overview (no inference)

Not emitted, with reasons (reported in --check and the spec):
- relationship graph: related_capabilities entries are untyped until R-1;
  a typed graph would fabricate semantics (CR-47 §6.3/§8.4).

Run: python3 scripts/generate_discovery_views.py [--check] [--self-test]
"""
from __future__ import annotations

import argparse
import re
import sys
import tempfile
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
ENTITIES = REPO_ROOT / "entities" / "v1-alpha"
VIEWS = REPO_ROOT / "docs" / "views"

HEADER = ("<!-- GENERATED by scripts/generate_discovery_views.py (CR-DEA-BC-47). "
          "Do not edit; regenerate with the script. -->")


def norm(s: str) -> str:
    return re.sub(r"\s+", " ", str(s or "")).strip()


def esc(s: str) -> str:
    return str(s).replace("|", "\\|")


def load_entities(root: Path) -> list[dict]:
    out = []
    ent_dir = root / "entities" / "v1-alpha"
    for d in sorted(ent_dir.iterdir()):
        if not d.is_dir():
            continue
        for f in sorted(d.glob("capabilities-*.yaml")):
            rec = yaml.safe_load(f.read_text(encoding="utf-8"))
            if isinstance(rec, dict) and rec.get("type") == "BusinessCapability":
                out.append({"dir": d, "file": f, "rec": rec})
    return out


def rel_link_from_views(target: Path, root: Path) -> str:
    import os
    return Path(os.path.relpath(target, root / "docs" / "views")).as_posix()


def view_index(ents: list[dict], root: Path) -> str:
    lines = [HEADER, "", "# Canonical Capability Index", "",
             f"{len(ents)} canonical first-order business capabilities. Derived from "
             "the canonical records; identity and content live in the records, not here.",
             "", "| Capability | Primary ECF | Definition | Provenance | Record · README |",
             "|---|---|---|---|---|"]
    for e in sorted(ents, key=lambda e: e["rec"]["name"]):
        rec = e["rec"]
        prim = (rec.get("ecf") or {}).get("primary") or {}
        coord = f"{prim.get('domain', '—')} / {prim.get('stage', '—')}"
        prov = rec.get("provenance") or {}
        stages = [s.get("stage", "") for s in prov.get("ladder_passage") or []]
        prov_s = "→".join(stages) if stages else "—"
        lp_rec = rel_link_from_views(e["file"], root)
        lp_readme = rel_link_from_views(e["dir"] / "README.md", root)
        lines.append(f"| [{rec['name']}]({lp_readme}) | {coord} | {esc(norm(rec.get('definition','')))[:180]} "
                     f"| {prov_s} | [record]({lp_rec}) |")
    return "\n".join(lines) + "\n"


def view_classification(ents: list[dict], root: Path) -> str:
    cells: dict[tuple[str, str], list[str]] = {}
    for e in ents:
        rec = e["rec"]
        ecf = rec.get("ecf") or {}
        prim = ecf.get("primary") or {}
        if prim:
            cells.setdefault((prim.get("domain", ""), prim.get("stage", "")), []).append(rec["name"])
    lines = [HEADER, "", "# Capability Classification (ECF)", "",
             "Grouped by each capability's governed primary ECF coordinate (semantic "
             "center of gravity; secondary coordinates in the records). Same-cell "
             "co-location implies no equivalence, hierarchy, or interchangeability.",
             ""]
    for (dom, stage) in sorted(cells):
        lines.append(f"## {dom} / {stage}")
        lines.append("")
        for n in sorted(cells[(dom, stage)]):
            lines.append(f"- {n}")
        lines.append("")
    return "\n".join(lines) + "\n"


def view_related(ents: list[dict], root: Path) -> str:
    by_id = {e["rec"]["id"]: e for e in ents}
    lines = [HEADER, "", "# Related Capability References", "",
             "Recorded `related_capabilities` references between canonical capabilities. "
             "Typed assertions (CR-DEA-BC-53: depends-on / realizes / specializes, with rationale) "
             "are rendered with their type; legacy bare entries are untyped associations whose "
             "semantics remain unresolved. No graph is emitted (CR-47 §6.3).",
             "| From | Reference | Type |", "|---|---|---|"]
    for e in sorted(ents, key=lambda e: e["rec"]["name"]):
        rec = e["rec"]
        rels = rec.get("related_capabilities") or []
        if not rels:
            continue
        for r in rels:
            if isinstance(r, dict):
                tgt = r.get("id")
                label = f"[{by_id[tgt]['rec']['name']}]({rel_link_from_views(by_id[tgt]['dir'] / 'README.md', root)})" if tgt in by_id else f"`{tgt}` (unresolved)"
                lines.append(f"| [{rec['name']}]({rel_link_from_views(e['dir'] / 'README.md', root)}) | {label} | `{r.get('type','')}` |")
            elif r in by_id:
                lines.append(f"| [{rec['name']}]({rel_link_from_views(e['dir'] / 'README.md', root)}) | [{by_id[r]['rec']['name']}]({rel_link_from_views(by_id[r]['dir'] / 'README.md', root)}) | — (untyped) |")
            else:
                lines.append(f"| [{rec['name']}]({rel_link_from_views(e['dir'] / 'README.md', root)}) | `{r}` (unresolved) | — (untyped) |")
    return "\n".join(lines) + "\n"


def view_outcomes(ents: list[dict], root: Path) -> str:
    lines = [HEADER, "", "# Outcomes and Business Objects Overview", "",
             "Outcome (intended contribution, never a guarantee) and business-object "
             "focus per canonical record. Shared objects or outcomes imply **no** "
             "dependency or hierarchy between capabilities (CR-47 §6.4).",
             "| Capability | Outcome | Business object |", "|---|---|---|"]
    for e in sorted(ents, key=lambda e: e["rec"]["name"]):
        rec = e["rec"]
        lines.append(f"| [{rec['name']}]({rel_link_from_views(e['dir'] / 'README.md', root)}) "
                     f"| {esc(norm(rec.get('outcome','')))} | {esc(rec.get('business_object','—'))} |")
    return "\n".join(lines) + "\n"


VIEWS_SPEC = [
    ("CAPABILITY-INDEX.md", view_index),
    ("ECF-CLASSIFICATION.md", view_classification),
    ("RELATED-CAPABILITIES.md", view_related),
    ("OUTCOMES-OVERVIEW.md", view_outcomes),
]


def generate(root: Path) -> dict[str, str]:
    ents = load_entities(root)
    return {name: fn(ents, root) for name, fn in VIEWS_SPEC}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="verify committed views match regeneration; exit 1 on drift")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args(argv)

    if args.self_test:
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            ent = root / "entities" / "v1-alpha" / "cap-a-aaaaaa"
            ent.mkdir(parents=True)
            (ent / "capabilities-capability-cap-a-aaaaaa.yaml").write_text(
                "id: capabilities:capability-cap-a-aaaaaa\ntype: BusinessCapability\n"
                "name: Cap A\ndefinition: The ability to A.\nversion: 1.0.0\n"
                "lifecycle_status: active\noutcome: As are achieved.\nbusiness_object: A\n"
                "related_capabilities: []\necf:\n  primary:\n    domain: d-one\n    stage: s-one\n")
            out = generate(root)
            assert "Cap A" in out["CAPABILITY-INDEX.md"]
            assert "## d-one / s-one" in out["ECF-CLASSIFICATION.md"]
            assert "As are achieved." in out["OUTCOMES-OVERVIEW.md"]
            out2 = generate(root)
            assert out == out2  # deterministic
        print("self-test PASS")
        return 0

    outputs = generate(REPO_ROOT)
    if args.check:
        stale = []
        for name, _ in VIEWS_SPEC:
            target = VIEWS / name
            if not target.is_file() or target.read_text(encoding="utf-8") != outputs[name]:
                stale.append(name)
        if stale:
            print(f"Discovery views (CR-DEA-BC-47): STALE — regenerate needed for: {', '.join(stale)}")
            return 1
        print("Discovery views (CR-DEA-BC-47): fresh (4 views match regeneration)")
        return 0

    VIEWS.mkdir(parents=True, exist_ok=True)
    for name, content in outputs.items():
        (VIEWS / name).write_text(content, encoding="utf-8")
    print(f"Discovery views (CR-DEA-BC-47): generated {len(outputs)} views in docs/views/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
